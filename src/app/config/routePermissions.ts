export function getRoutePermission(pathname: string): string | null {
  const match = ROUTE_PERMISSIONS.find(({ pattern }) => {
    const base = pattern.replace(/:[^/]+/g, "[^/]+")
    return new RegExp(`^${base}(?:/|$)`).test(pathname)
  })
  return match?.permission ?? "dashboard.view"
}
